@bot.command(name="link")
async def cmd_link(ctx, code: str = None):
    """Link your Steam account to Discord using in-game /link code"""
    if not code:
        embed = discord.Embed(
            title="🔗 LINK STEAM ACCOUNT TO DISCORD",
            description=(
                "To link your Steam account, follow these **3 simple steps**:\n\n"
                "1. Connect to our Rust server:\n"
                "```bash\nclient.connect 157.85.95.101:29416\n```\n"
                "2. Type **`/link`** in the in-game chat to get your 6-digit code.\n"
                "3. Return here and type: **`/link <code>`**\n"
                "👉 *Example:* `/link 849201`\n"
                "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
            ),
            color=0xF1C40F
        )
        embed.set_footer(text="Verification grants access to the Verified Survivor role and skin trade donations.")
        await ctx.send(embed=embed)
        return

    code_clean = code.strip()
    msg = await ctx.send("⏳ Verifying your code with the Rust server...")

    loop = asyncio.get_running_loop()
    success, steam_id, player_name, err = await loop.run_in_executor(None, verify_ingame_code, code_clean)

    if not success:
        embed_err = discord.Embed(
            title="❌ Verification Failed",
            description=(
                f"**Error:** {err}\n\n"
                "Please make sure you are currently on the server, type **`/link`** in game chat, and copy the 6-digit code."
            ),
            color=0xE74C3C
        )
        await msg.edit(content=None, embed=embed_err)
        return

    # Сохраняем в локальную базу данных
    data = load_data()
    user_id_str = str(ctx.author.id)
    data[user_id_str] = {
        "steam_id": steam_id,
        "player_name": player_name,
        "discord_tag": str(ctx.author),
        "linked_at": datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")
    }
    save_data(data)

    # Выдаем роль "⚔️ | Verified Survivor"
    role = discord.utils.get(ctx.guild.roles, name="⚔️ | Verified Survivor")
    if role:
        try:
            await ctx.author.add_roles(role)
        except Exception as e:
            print(f"[-] Could not grant role: {e}")

    embed_success = discord.Embed(
        title="🎉 STEAM ACCOUNT SUCCESSFULLY VERIFIED!",
        description=(
            f"Welcome to the community, {ctx.author.mention}!\n\n"
            f"👤 **Player Name:** `{player_name}`\n"
            f"🆔 **SteamID64:** `{steam_id}`\n"
            f"🎖️ **Role Granted:** `⚔️ | Verified Survivor`\n\n"
            f"You can now purchase VIP packages via Steam skins using **`/buy`**!"
        ),
        color=0x2ECC71
    )
    embed_success.set_thumbnail(url=ctx.author.display_avatar.url)
    await msg.edit(content=None, embed=embed_success)

