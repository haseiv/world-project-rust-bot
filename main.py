    if message.author.bot:
        return

    if bot.user.mentioned_in(message) or message.content.startswith("?"):
        clean_content = message.content.replace(f"<@{bot.user.id}>", "").strip("? ")
        data = load_data()
        user_info = data.get(str(message.author.id))
