# 🎮 IN-GAME STEAM LINK VERIFICATION (VIA SFTP TO RUST SERVER)
# ==============================================================================
def verify_ingame_code(code_to_check):
    """
    Connects to Rust server via SFTP and verifies the 6-digit code generated by /link in-game.
    Returns (success, steam_id, player_name, error_msg)
    """
    try:
        ssh = paramiko.SSHClient()
        ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
        ssh.connect(config.SFTP_HOST, port=config.SFTP_PORT, username=config.SFTP_USER, password=config.SFTP_PASS, timeout=12)
        sftp = ssh.open_sftp()

        remote_data_file = f"{config.SFTP_BASE_DIR}/oxide/data/SteamLink_Data.json"
        
        try:
            with sftp.open(remote_data_file, "r") as f:
                link_data = json.loads(f.read().decode("utf-8"))
        except Exception:
            link_data = {"PendingCodes": {}, "LinkedSteamIDs": []}

        pending = link_data.get("PendingCodes", {})
        code_str = str(code_to_check).strip()

        if code_str not in pending:
            sftp.close()
            ssh.close()
            return False, None, None, "Code not found or expired. Type `/link` in-game to generate a new one."

        code_info = pending[code_str]
        steam_id = str(code_info.get("SteamID"))
        player_name = code_info.get("PlayerName", "Survivor")

        # Mark as linked on the server
        del pending[code_str]
        linked_list = link_data.get("LinkedSteamIDs", [])
        if int(steam_id) not in linked_list:
            linked_list.append(int(steam_id))
        link_data["LinkedSteamIDs"] = linked_list

        with sftp.open(remote_data_file, "w") as f:
            f.write(json.dumps(link_data, indent=2))

        sftp.close()
        ssh.close()
        return True, steam_id, player_name, None

    except Exception as e:
        print(f"[-] SFTP Link Verification Error: {e}")
        return False, None, None, f"Connection to game server failed: {e}"

